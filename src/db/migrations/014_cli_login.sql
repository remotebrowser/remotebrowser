CREATE TABLE cli_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id text NOT NULL,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES users(id),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
  token_hash text NOT NULL,
  -- What the CLI told us when the login started.
  device_name text,
  ip_address text,
  user_agent text,
  created_timestamp bigint NOT NULL,
  expires_timestamp bigint NOT NULL CHECK (expires_timestamp > created_timestamp),
  last_used_timestamp bigint
);

CREATE UNIQUE INDEX cli_sessions_token_hash_idx ON cli_sessions (token_hash);
CREATE UNIQUE INDEX cli_sessions_public_id_unique_idx ON cli_sessions (public_id);
CREATE INDEX cli_sessions_workspace_user_idx ON cli_sessions (workspace_id, user_id);
CREATE INDEX cli_sessions_expires_idx ON cli_sessions (expires_timestamp);

-- Pending logins of the device flow. Kept in the database, so several server
-- instances share them and a restart keeps them.
CREATE TABLE device_authorizations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_code_hash text NOT NULL,
  user_code text NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'denied', 'used')),
  device_name text,
  ip_address text,
  user_agent text,
  created_timestamp bigint NOT NULL,
  expires_timestamp bigint NOT NULL,
  last_polled_timestamp bigint,
  -- Set on approval: who approved, and for which workspace.
  user_id bigint REFERENCES users(id) ON DELETE CASCADE,
  workspace_id bigint REFERENCES workspaces(id) ON DELETE CASCADE,
  approved_timestamp bigint
);

CREATE UNIQUE INDEX device_authorizations_device_code_hash_idx ON device_authorizations (device_code_hash);
-- Two pending logins must never share a code the user types.
CREATE UNIQUE INDEX device_authorizations_pending_user_code_idx ON device_authorizations (user_code)
  WHERE status = 'pending';
CREATE INDEX device_authorizations_expires_idx ON device_authorizations (expires_timestamp);
