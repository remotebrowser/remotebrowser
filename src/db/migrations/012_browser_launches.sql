-- One row per launch, kept after the browser is terminated, so the launch rate
-- per workspace cannot be dodged by launching and terminating in a loop.
CREATE TABLE browser_launches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES users(id),
  launched_timestamp bigint NOT NULL
);

CREATE INDEX browser_launches_workspace_time_idx ON browser_launches (workspace_id, launched_timestamp);
CREATE INDEX browser_launches_time_idx ON browser_launches (launched_timestamp);
