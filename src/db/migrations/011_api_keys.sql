CREATE TABLE api_keys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id text NOT NULL,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES users(id),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
  key_hash text NOT NULL,
  key_preview text NOT NULL,
  created_timestamp bigint NOT NULL,
  expires_timestamp bigint NOT NULL CHECK (expires_timestamp > created_timestamp),
  last_used_timestamp bigint
);

CREATE UNIQUE INDEX api_keys_key_hash_idx ON api_keys (key_hash);
CREATE UNIQUE INDEX api_keys_public_id_unique_idx ON api_keys (public_id);
CREATE INDEX api_keys_workspace_user_idx ON api_keys (workspace_id, user_id);
CREATE INDEX api_keys_expires_idx ON api_keys (expires_timestamp);
